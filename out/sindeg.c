double
sindeg(double d)
{
    int     n;

    if (d < 0.0)
	return (-sindeg(-d));
    n = ((int) d) % 360;
    switch (n / 90) {
    case 0:
	return (sin_tab[n]);
    case 1:
	return (sin_tab[180 - n]);
    case 2:
	return (-sin_tab[n - 180]);
    case 3:
	return (-sin_tab[360 - n]);
    }
    return (0.0);
}

double
cosdeg(double d)
{
    return (sindeg(d + 90.0));
}

double
atan2deg(double y, double x)
{
    int     n1, n2, nn;
    double  d, s;

    d = x * x + y * y;
    if (d == 0.0)
	return (0.0);		/* degenerate case */
    if (y == 0.0)
	return ((x > 0.0) ? 0.0 : 180.0);
    else if (x == 0.0)
	return ((y > 0.0) ? 90.0 : 270.0);

    s = ((y > 0.0) ? y : -y) / d;
    n1 = 0;
    n2 = 90;
    do {
	nn = (n1 + n2) / 2;
	if (sin_tab[nn] <= s)
	    n1 = nn;
	else
	    n2 = nn;
    } while ((n2 - n1) > 1);

    if (y > 0.0)
	d = (x > 0.0) ? nn : 180.0 - nn;
    else
	d = (x > 0.0) ? 180.0 + nn : 360.0 - nn;
    return (d);
}
